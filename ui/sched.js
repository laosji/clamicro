/**
 * 把「一帧之内的许多次请求」并成一次，并且**不让旧答案盖掉新答案**。
 *
 * ## 起因：一次开页 105 个请求
 *
 * 两个页面都把 SSE 直接接到刷新上：
 *
 *     es.addEventListener('event', refresh)      // ui/session.html
 *     es.addEventListener('session', refresh)    // ui/home.html
 *
 * 而 `/api/stream` 在**连上的那一刻会把历史事件全量重放**（server.mjs 里
 * `store.events(lastId)`，首次连 lastId=0，上限三千条）。于是一个有 85 条
 * 事件的会话，打开一次页面实测发出 **105 个 `/api/sessions/:id`**，每个都拉
 * 完整负载、每个都重画整条时间线。真实的长会话在服务端能存到两千条，
 * 那就是开一次页面几千个来回——在手机上，走 Wi-Fi。
 *
 * 实时也一样贵：首页实测 **20 次工具调用 = 60 个请求**（每条事件三个接口）。
 * 对面每敲一个命令，你的手机就去问三遍。
 *
 * home.html 早就为**重绘**写过这个东西（`scheduleRender`，注释里写着
 * 「逐条重绘既卡又没意义——中间那些帧没人看得见」），只是没往前挪一步管到
 * **请求**。同一句话对网络更成立：中间那些响应不但没人看，还每个都要过网。
 *
 * ## 另一半：并发的响应会乱序回来
 *
 * 这不是浪费，是错。同一页里发 40 次，实测回来的顺序是
 *
 *     1, 2, 3, 14, 15, 4, 16, 5, 17, 6, 18, 7 …
 *
 * 第 14 个比第 4 个先到。最后落地的那一份不保证是最新的那一份——
 * 屏幕上可以稳定停在一个**比已经收到过的还旧**的状态，而且没有任何报错。
 * 页面看着在正常刷新，内容是过期的，这正是这个仓库最不能容忍的那类假象。
 *
 * 所以 `run` 拿到一个 `isStale()`：取数据可以慢慢取，但**往屏幕上写之前
 * 先问一句自己是不是已经过时了**。检查点放在哪只有调用方知道——它才清楚
 * 哪一段是「取」、哪一段是「写」。
 *
 * ## 为什么是 rAF
 *
 * 后台标签页里 rAF 是挂起的，于是页面切到后台就自然停止请求——这正是想要
 * 的（省电、省流量），而两个页面都在 `visibilitychange` 里回前台补一次全量。
 * 用 setTimeout 反而会在没人看的时候接着掏流量。
 *
 * raf 可注入：测试里换成手动泵，才能在不真等一帧的前提下断言合并行为。
 */
function coalesced(run, { raf = requestAnimationFrame } = {}) {
  let queued = false;
  let latest = 0;

  /* 号码在**这一轮开跑时**就发，不是等它回来才发。反过来的话
     （回来才编号）两个并发的轮次会都认为自己最新，而那正是要挡的情况。 */
  const start = () => {
    const mine = ++latest;
    return run(() => mine !== latest);
  };

  function schedule() {
    if (queued) return;
    queued = true;
    raf(() => { queued = false; start(); });
  }

  /**
   * **马上跑，不等下一帧，并且把 promise 还给调用方。**
   *
   * 合并是为了挡住机器造出来的洪水（SSE 重放、一轮里连续几十个工具调用）。
   * 人点下去的那一次不在此列：只有一次，不需要合并，而且调用方通常要
   * `await` 它——按下暂停之后那个图标该马上变。走 schedule 的话 `await`
   * 会立刻返回（排程函数不返回 promise），代码读起来像等过了，其实没有。
   *
   * 首屏那一次也走这里：rAF 在后台标签页是挂起的，让**第一次**渲染依赖它，
   * 等于页面可能什么都不画。合并省的是重复，不该省掉唯一的那一次。
   *
   * 排序保护照旧——`now()` 同样领号，晚到的旧响应一样会被 isStale 拦下。
   */
  schedule.now = start;
  return schedule;
}
